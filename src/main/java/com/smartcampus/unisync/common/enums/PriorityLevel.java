package com.smartcampus.unisync.common.enums;

/**
 * Represents the priority level of a ticket.
 * Used to indicate how urgently the issue needs to be handled.
 */
public enum PriorityLevel {
    LOW,    // Not urgent — can be handled when convenient
    MEDIUM, // Moderately urgent — should be handled soon
    HIGH    // Very urgent — needs immediate attention
}
